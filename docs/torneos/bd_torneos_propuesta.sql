-- =====================================================================
-- Propuesta de base de datos - Módulo de Torneos (Grupo 4)
-- Proyecto SEMILLERO (repositorio semillero-app) - PostgreSQL 17 en Docker
-- Versión 3.0 (21/10/2026)
--
-- Parte de la BD acordada entre los grupos (la de dbdiagram) y NO la cambia:
-- solo le agrega columnas y tablas que torneos necesita.
--
-- Importante: en el repositorio semillero-app las tablas las crea Hibernate
-- a partir de las entidades JPA (perfil dev, ddl-auto=update). Este script
-- es la referencia para escribir las entidades de torneos y para revisar el
-- diseño en una base PostgreSQL limpia. Las reglas que no se pueden poner
-- con anotaciones JPA (choque de canchas, vistas) van en el código Java.
--
-- Secciones:
--   A. BD acordada entre grupos (tal cual la crea el repositorio)
--   B. Tablas compartidas nuevas que pide torneos
--   C. Tablas propias del módulo de torneos
--   D. Columnas que torneos agrega a tablas de la BD acordada
--   E. Datos iniciales
-- =====================================================================


-- =====================================================================
-- A. BD ACORDADA ENTRE GRUPOS
--    No la crea torneos: ya existe en el repositorio (entidades del
--    módulo data). Está aquí solo para que el script corra completo.
-- =====================================================================

CREATE TABLE pais (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_pais varchar(30)
);

CREATE TABLE ciudad (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_ciudad varchar(30),
    pais_id       bigint REFERENCES pais(id)
);

CREATE TABLE clubes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_club varchar(15),
    ciudad_id   bigint REFERENCES ciudad(id)
);

CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  varchar(255),
    email                 varchar(255),
    telefono_usuario      varchar(20),
    doc_identidad_usuario varchar(20),
    password_hash         varchar(255),
    nombres               varchar(35),
    apellidos             varchar(35)
);

CREATE TABLE administrador (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint REFERENCES users(id)
);

CREATE TABLE usuarios_club (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint REFERENCES users(id)
);

CREATE TABLE usuario_trabaja (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuarios_club_id  bigint REFERENCES usuarios_club(id),
    tipo_usuario_club char(2),
    clubes_id         bigint REFERENCES clubes(id)
);

CREATE TABLE jugadores (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pierna_habil        char(1),
    fecha_nacimiento    date,
    altura              float,
    peso                float,
    descripcion_jugador varchar(255),
    users_id            bigint REFERENCES users(id)
);

CREATE TABLE posiciones (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posicion        varchar(100),
    codigo_posicion char(4)
);

CREATE TABLE posiciones_jugador (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posiciones_id bigint REFERENCES posiciones(id),
    jugadores_id  bigint REFERENCES jugadores(id)
);

CREATE TABLE fichado (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_fichaje       timestamp,
    fecha_final_fichaje timestamp,
    jugadores_id        bigint REFERENCES jugadores(id),
    clubes_id           bigint REFERENCES clubes(id)
);

CREATE TABLE pruebas (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_prueba     date,
    hora_prueba      time,
    clubes_id        bigint REFERENCES clubes(id),
    usuarios_club_id bigint REFERENCES usuarios_club(id)
);

CREATE TABLE clinica_de_pago (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio_clinica timestamp,
    fecha_fin_clinica    timestamp,
    clubes_id            bigint REFERENCES clubes(id),
    usuarios_club_id     bigint REFERENCES usuarios_club(id)
);

CREATE TABLE videos (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo_video varchar(100),
    link_video   varchar(100),
    jugadores_id bigint REFERENCES jugadores(id)
);

CREATE TABLE conversa (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje         varchar(255),
    users_envia_id  bigint REFERENCES users(id),
    users_recibe_id bigint REFERENCES users(id)
);

-- Partidos: tabla compartida de la BD acordada
CREATE TABLE partidos (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio      timestamp NOT NULL,
    fecha_fin         timestamp,
    club_local_id     bigint NOT NULL REFERENCES clubes(id),
    club_visitante_id bigint NOT NULL REFERENCES clubes(id),
    estado            varchar(20) NOT NULL
                      CHECK (estado IN ('PROGRAMADO','EN_CURSO','FINALIZADO','CANCELADO')),
    CONSTRAINT chk_clubes_distintos CHECK (club_local_id <> club_visitante_id)
);

-- Participación de cada jugador en un partido (la usan torneos y el microservicio de video)
CREATE TABLE participaciones_partido (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id         bigint NOT NULL REFERENCES partidos(id),
    jugadores_id        bigint NOT NULL REFERENCES jugadores(id),
    clubes_id           bigint NOT NULL REFERENCES clubes(id),
    es_titular          boolean NOT NULL,
    dorsal              smallint,
    minuto_entrada      smallint NOT NULL DEFAULT 0,
    minuto_salida       smallint,
    velocidad_prom      float,
    distancia_recorrida float,
    CONSTRAINT uk_participacion_jugador UNIQUE (partidos_id, jugadores_id)
);

CREATE INDEX idx_partidos_fecha_inicio ON partidos (fecha_inicio);
CREATE INDEX idx_partidos_local        ON partidos (club_local_id);
CREATE INDEX idx_partidos_visitante    ON partidos (club_visitante_id);
CREATE INDEX idx_participacion_club    ON participaciones_partido (partidos_id, clubes_id);


