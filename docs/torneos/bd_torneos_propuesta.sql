-- Roles del sistema. La tabla "administrador" se mantiene como está;
-- estos roles cubren a organizador, entrenador, mesa de control y consulta.
CREATE TABLE roles (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(50) NOT NULL
);

CREATE TABLE usuarios_roles (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint NOT NULL REFERENCES users(id),
    roles_id bigint NOT NULL REFERENCES roles(id),
    UNIQUE (users_id, roles_id)
);

-- Documentación del jugador (CI, certificado de nacimiento, apto médico...)
CREATE TABLE documentos_jugador (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugadores_id      bigint NOT NULL REFERENCES jugadores(id),
    tipo              varchar(25) NOT NULL
                      CHECK (tipo IN ('CI','CERTIFICADO_NACIMIENTO','APTO_MEDICO','AUTORIZACION_PADRES','SEGURO')),
    numero            varchar(30),
    fecha_emision     date,
    fecha_vencimiento date,
    estado            varchar(15) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (estado IN ('PENDIENTE','VIGENTE','VENCIDO','RECHAZADO'))
);

-- Bitácora común para cambios importantes y accesos rechazados
CREATE TABLE auditoria (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo         varchar(20) NOT NULL,   -- TORNEOS, FICHA, RENDIMIENTO, SCOUTING
    tabla          varchar(50) NOT NULL,
    registro_id    bigint,
    accion         varchar(30) NOT NULL,   -- CREAR, MODIFICAR, CAMBIO_ESTADO, REABRIR, ACCESO_DENEGADO...
    valor_anterior jsonb,
    valor_nuevo    jsonb,
    motivo         varchar(255),
    users_id       bigint REFERENCES users(id),
    fecha          timestamp NOT NULL DEFAULT now()
);

-- Notificaciones para la web y la app móvil
CREATE TABLE notificaciones (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint NOT NULL REFERENCES users(id),
    modulo   varchar(20) NOT NULL,
    titulo   varchar(100) NOT NULL,
    mensaje  varchar(500) NOT NULL,
    leida    boolean NOT NULL DEFAULT false,
    fecha    timestamp NOT NULL DEFAULT now()
);


-- =====================================================================
-- C. TABLAS PROPIAS DEL MÓDULO DE TORNEOS
--    Solo torneos escribe en ellas.
-- =====================================================================

-- HU 3 - Sedes y canchas
CREATE TABLE sedes (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    varchar(80)  NOT NULL,
    direccion varchar(150) NOT NULL,
    ciudad_id bigint NOT NULL REFERENCES ciudad(id)
);

CREATE TABLE canchas (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sedes_id        bigint NOT NULL REFERENCES sedes(id),
    nombre          varchar(50) NOT NULL,
    tipo_superficie varchar(20) NOT NULL
                    CHECK (tipo_superficie IN ('CESPED_NATURAL','CESPED_SINTETICO','TIERRA','CEMENTO','PISO_TECHADO')),
    largo_m         numeric(5,1),
    ancho_m         numeric(5,1),
    techada         boolean NOT NULL DEFAULT false,
    iluminacion     boolean NOT NULL DEFAULT false,
    vestuarios      boolean NOT NULL DEFAULT false,
    descripcion     varchar(255),
    activa          boolean NOT NULL DEFAULT true,
    UNIQUE (sedes_id, nombre)
);

-- HU 1 - Torneo (interno o campeonato externo)
CREATE TABLE torneos (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                   varchar(100) NOT NULL,
    temporada                smallint NOT NULL,
    tipo                     varchar(15) NOT NULL CHECK (tipo IN ('OFICIAL','AMISTOSO','PRETEMPORADA')),
    ambito                   varchar(10) NOT NULL DEFAULT 'INTERNO'
                             CHECK (ambito IN ('INTERNO','EXTERNO')),  -- EXTERNO = campeonato de otra institución
    organizador_externo      varchar(100),
    formato                  varchar(25) NOT NULL
                             CHECK (formato IN ('LIGA','ELIMINACION_DIRECTA','GRUPOS_FASE_FINAL')),
    ida_vuelta               boolean NOT NULL DEFAULT false,
    fecha_inicio             date NOT NULL,
    fecha_fin                date NOT NULL,
    fecha_limite_inscripcion date NOT NULL,
    estado                   varchar(25) NOT NULL DEFAULT 'BORRADOR'
                             CHECK (estado IN ('BORRADOR','INSCRIPCIONES_ABIERTAS','EN_CURSO','FINALIZADO','CANCELADO')),
    users_id                 bigint NOT NULL REFERENCES users(id),  -- organizador que lo creó
    fecha_creacion           timestamp NOT NULL DEFAULT now(),
    CHECK (fecha_fin >= fecha_inicio),
    CHECK (fecha_limite_inscripcion <= fecha_inicio),
    CHECK (ambito = 'INTERNO' OR organizador_externo IS NOT NULL)
);

-- HU 2 - Reglamento (uno por torneo)
CREATE TABLE reglamentos (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneos_id                  bigint NOT NULL UNIQUE REFERENCES torneos(id),
    puntos_victoria             smallint NOT NULL DEFAULT 3,
    puntos_empate               smallint NOT NULL DEFAULT 1,
    puntos_derrota              smallint NOT NULL DEFAULT 0,
    umbral_amarillas            smallint NOT NULL DEFAULT 3,
    fechas_suspension_amarillas smallint NOT NULL DEFAULT 1,
    fechas_suspension_roja      smallint NOT NULL DEFAULT 1,
    goles_walkover              smallint NOT NULL DEFAULT 3,
    fecha_corte                 date NOT NULL,                 -- por defecto 31/12 de la temporada
    min_jugadores               smallint NOT NULL,
    max_jugadores               smallint NOT NULL,
    descanso_minimo_min         smallint NOT NULL DEFAULT 60,  -- minutos entre partidos del mismo equipo
    CHECK (min_jugadores <= max_jugadores)
);

CREATE TABLE criterios_desempate (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(50) NOT NULL
);

CREATE TABLE reglamento_desempates (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reglamentos_id         bigint NOT NULL REFERENCES reglamentos(id),
    criterios_desempate_id bigint NOT NULL REFERENCES criterios_desempate(id),
    orden                  smallint NOT NULL CHECK (orden > 0),
    UNIQUE (reglamentos_id, orden),
    UNIQUE (reglamentos_id, criterios_desempate_id)
);

-- HU 1 - Categorías del torneo con su rango de edad
CREATE TABLE torneo_categorias (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneos_id          bigint NOT NULL REFERENCES torneos(id),
    nombre              varchar(20) NOT NULL,   -- Sub-12, Sub-14, Categoría 2014...
    edad_minima         smallint,               -- edad cumplida a la fecha de corte
    edad_maxima         smallint NOT NULL,
    cupo_maximo         smallint NOT NULL CHECK (cupo_maximo >= 2),
    duracion_tiempo_min smallint NOT NULL,      -- duración de cada tiempo
    jugadores_en_cancha smallint NOT NULL,
    max_sustituciones   smallint,
    UNIQUE (torneos_id, nombre),
    CHECK (edad_minima IS NULL OR edad_minima <= edad_maxima)
);

-- Formato grupos con fase final
CREATE TABLE grupos (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_categorias_id bigint NOT NULL REFERENCES torneo_categorias(id),
    nombre               varchar(10) NOT NULL,
    UNIQUE (torneo_categorias_id, nombre)
);

-- HU 4 y HU 6 - Inscripción: el "equipo" es el club inscrito en una categoría
CREATE TABLE inscripciones_equipo (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_categorias_id bigint NOT NULL REFERENCES torneo_categorias(id),
    clubes_id            bigint NOT NULL REFERENCES clubes(id),
    grupos_id            bigint REFERENCES grupos(id),
    cabeza_serie         smallint,
    estado               varchar(15) NOT NULL DEFAULT 'PENDIENTE'
                         CHECK (estado IN ('PENDIENTE','OBSERVADA','APROBADA','RECHAZADA')),
    motivo               varchar(255),
    lista_confirmada     boolean NOT NULL DEFAULT false,
    users_id             bigint NOT NULL REFERENCES users(id),   -- entrenador que inscribe
    fecha_inscripcion    timestamp NOT NULL DEFAULT now(),
    UNIQUE (torneo_categorias_id, clubes_id),
    CHECK (estado NOT IN ('OBSERVADA','RECHAZADA') OR motivo IS NOT NULL)
);

-- HU 5 - Lista de buena fe por campeonato (interno o externo).
-- torneos_id lo pone el servicio al guardar (copia del torneo de la inscripción)
-- y sirve para que un jugador esté en un solo equipo por torneo.
CREATE TABLE lista_buena_fe (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripciones_equipo_id bigint NOT NULL REFERENCES inscripciones_equipo(id),
    torneos_id              bigint NOT NULL REFERENCES torneos(id),
    jugadores_id            bigint NOT NULL REFERENCES jugadores(id),
    posiciones_id           bigint REFERENCES posiciones(id),
    dorsal                  smallint NOT NULL CHECK (dorsal BETWEEN 1 AND 99),
    habilitado              boolean NOT NULL DEFAULT true,
    motivo_inhabilitacion   varchar(255),
    fecha_alta              timestamp NOT NULL DEFAULT now(),
    UNIQUE (inscripciones_equipo_id, dorsal),
    UNIQUE (torneos_id, jugadores_id)
);

-- HU 8 - Historial de reprogramaciones
CREATE TABLE reprogramaciones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id         bigint NOT NULL REFERENCES partidos(id),
    fecha_inicio_anterior timestamp,
    canchas_anterior_id bigint REFERENCES canchas(id),
    fecha_inicio_nueva  timestamp NOT NULL,
    canchas_nueva_id    bigint NOT NULL REFERENCES canchas(id),
    motivo              varchar(255) NOT NULL,
    users_id            bigint NOT NULL REFERENCES users(id),
    fecha               timestamp NOT NULL DEFAULT now()
);

-- HU 9 - Planilla del partido (cabecera). Los jugadores de la planilla se
-- guardan en participaciones_partido, la tabla acordada entre grupos.
CREATE TABLE planillas (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id           bigint NOT NULL UNIQUE REFERENCES partidos(id),
    estado                varchar(15) NOT NULL DEFAULT 'BORRADOR'
                          CHECK (estado IN ('BORRADOR','CONFIRMADA')),
    observaciones_arbitro text,
    users_id              bigint NOT NULL REFERENCES users(id),   -- mesa de control
    fecha_confirmacion    timestamp
);

CREATE TABLE planilla_cuerpo_tecnico (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planillas_id    bigint NOT NULL REFERENCES planillas(id),
    clubes_id       bigint NOT NULL REFERENCES clubes(id),
    nombre_completo varchar(100) NOT NULL,
    cargo           varchar(30) NOT NULL,
    users_id        bigint REFERENCES users(id)
);

-- HU 10 - Eventos del partido. Apuntan a participaciones_partido.
CREATE TABLE eventos_partido (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id                 bigint NOT NULL REFERENCES partidos(id),
    tipo                        varchar(10) NOT NULL CHECK (tipo IN ('GOL','AMARILLA','ROJA','CAMBIO')),
    minuto                      smallint NOT NULL CHECK (minuto BETWEEN 0 AND 130),
    participaciones_partido_id  bigint NOT NULL REFERENCES participaciones_partido(id),  -- autor / amonestado / sale
    participacion_rel_id        bigint REFERENCES participaciones_partido(id),           -- asistencia / entra
    clubes_id                   bigint NOT NULL REFERENCES clubes(id),                   -- equipo al que suma el evento
    tipo_gol                    varchar(12) CHECK (tipo_gol IN ('JUGADA','PENAL','TIRO_LIBRE','AUTOGOL')),
    motivo                      varchar(150),
    users_id                    bigint NOT NULL REFERENCES users(id),
    fecha_registro              timestamp NOT NULL DEFAULT now(),
    CHECK ((tipo = 'GOL') = (tipo_gol IS NOT NULL)),
    CHECK (tipo <> 'CAMBIO' OR participacion_rel_id IS NOT NULL),
    CHECK (participacion_rel_id IS DISTINCT FROM participaciones_partido_id)
);

-- HU 13 - Sanciones y apelaciones
CREATE TABLE sanciones (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista_buena_fe_id bigint NOT NULL REFERENCES lista_buena_fe(id),  -- jugador dentro del torneo
    partidos_id       bigint REFERENCES partidos(id),                  -- partido que la originó
    origen            varchar(25) NOT NULL CHECK (origen IN ('ACUMULACION_AMARILLAS','ROJA','MANUAL')),
    fechas_suspension smallint NOT NULL CHECK (fechas_suspension > 0),
    fechas_cumplidas  smallint NOT NULL DEFAULT 0,
    motivo            varchar(255),
    estado            varchar(15) NOT NULL DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE','CUMPLIDA','ANULADA')),
    users_id          bigint REFERENCES users(id),   -- NULL cuando la genera el sistema
    fecha_registro    timestamp NOT NULL DEFAULT now(),
    CHECK (fechas_cumplidas BETWEEN 0 AND fechas_suspension),
    CHECK (origen <> 'MANUAL' OR motivo IS NOT NULL)
);

CREATE TABLE apelaciones (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sanciones_id       bigint NOT NULL REFERENCES sanciones(id),
    motivo             varchar(255) NOT NULL,
    estado             varchar(15) NOT NULL DEFAULT 'PENDIENTE'
                       CHECK (estado IN ('PENDIENTE','ACEPTADA','RECHAZADA','REDUCIDA')),
    resolucion         varchar(255),
    fechas_resueltas   smallint,
    users_id           bigint NOT NULL REFERENCES users(id),   -- quien presenta
    resuelto_por       bigint REFERENCES users(id),
    fecha_presentacion timestamp NOT NULL DEFAULT now(),
    fecha_resolucion   timestamp
);


-- =====================================================================
-- D. COLUMNAS QUE TORNEOS AGREGA A TABLAS DE LA BD ACORDADA
--    Todas son opcionales (aceptan NULL o tienen valor por defecto), así
--    el CRUD que ya existe en el repositorio sigue funcionando igual.
--    Se piden al grupo que mantiene cada tabla antes de agregarlas.
-- =====================================================================

-- partidos: lo que necesita un partido de torneo.
--   fecha_inicio = fecha y hora programada; fecha_fin = inicio + duración + margen.
--   Estados (se usan los acordados): PROGRAMADO, EN_CURSO, FINALIZADO (partido
--   cerrado o ganado por W.O.) y CANCELADO (partido anulado).
--   En un campeonato externo el rival se registra en clubes con datos mínimos.
ALTER TABLE partidos
    ADD COLUMN torneo_categorias_id bigint REFERENCES torneo_categorias(id),  -- NULL = partido fuera de torneo
    ADD COLUMN grupos_id            bigint REFERENCES grupos(id),
    ADD COLUMN fase                 varchar(15)
        CHECK (fase IN ('LIGA','GRUPOS','OCTAVOS','CUARTOS','SEMIFINAL','TERCER_PUESTO','FINAL')),
    ADD COLUMN jornada              smallint,                                   -- número de fecha
    ADD COLUMN canchas_id           bigint REFERENCES canchas(id),
    ADD COLUMN arbitro              varchar(100),
    ADD COLUMN mesa_control_id      bigint REFERENCES users(id),
    ADD COLUMN goles_local          smallint CHECK (goles_local >= 0),
    ADD COLUMN goles_visitante      smallint CHECK (goles_visitante >= 0),
    ADD COLUMN penales_local        smallint CHECK (penales_local >= 0),
    ADD COLUMN penales_visitante    smallint CHECK (penales_visitante >= 0),
    ADD COLUMN ganador_walkover_id  bigint REFERENCES clubes(id),
    ADD COLUMN partido_siguiente_id bigint REFERENCES partidos(id),             -- llave de eliminación directa
    ADD COLUMN fecha_cierre         timestamp,
    ADD COLUMN cerrado_por          bigint REFERENCES users(id),
    ADD CONSTRAINT chk_partido_torneo_fase
        CHECK (torneo_categorias_id IS NULL OR fase IS NOT NULL),
    ADD CONSTRAINT chk_walkover_club
        CHECK (ganador_walkover_id IS NULL OR ganador_walkover_id IN (club_local_id, club_visitante_id)),
    ADD CONSTRAINT chk_partido_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin > fecha_inicio);

CREATE INDEX idx_partidos_tc_estado ON partidos (torneo_categorias_id, estado);
CREATE INDEX idx_partidos_cancha    ON partidos (canchas_id, fecha_inicio);

-- participaciones_partido: es la planilla de jugadores de cada partido.
--   es_titular, dorsal, minuto_entrada y minuto_salida los llena torneos.
--   Suplente que no entró: minuto_entrada = 0 y minuto_salida = 0.
--   Expulsado: minuto_salida = minuto de la roja.
--   velocidad_prom y distancia_recorrida las llena el microservicio de video.
ALTER TABLE participaciones_partido
    ADD COLUMN capitan         boolean NOT NULL DEFAULT false,
    ADD COLUMN minutos_jugados smallint CHECK (minutos_jugados >= 0);  -- lo calcula torneos al cerrar

-- jugadores: estado del jugador (lo mantiene ficha técnica)
ALTER TABLE jugadores
    ADD COLUMN estado varchar(15) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','LESIONADO','INACTIVO','BAJA'));

-- Índices de torneos
CREATE INDEX idx_eventos_partido  ON eventos_partido (partidos_id);
CREATE INDEX idx_lista_bf_jugador ON lista_buena_fe (jugadores_id);
CREATE INDEX idx_sanciones_estado ON sanciones (estado);


