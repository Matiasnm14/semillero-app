package edu.upb.semillero.scouting;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;
import java.time.OffsetDateTime;
import java.sql.Timestamp;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.context.SecurityContextHolder;
import edu.upb.semillero.service.seguridad.UsuarioAutenticado;
import tools.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.AfterEach;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

class ScoutingRulesTest {
    @Test
    void duplicateResultsIncludeOnlyProspectsTheCallerCanAccess() {
        UUID visible = UUID.randomUUID();
        UUID restricted = UUID.randomUUID();

        assertThat(ScoutingProspectService.visibleDuplicateIds(List.of(visible, restricted), Set.of(visible)::contains))
                .containsExactly(visible);
    }

    @Test
    void prospectListMatchesDirectAccessAndKeepsPageResponseContract() {
        DriverManagerDataSource source = new DriverManagerDataSource(
                "jdbc:h2:mem:scouting-list-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE scouting_prospects (id uuid PRIMARY KEY, sensitive_payload bytea NOT NULL, identity_fingerprint varchar(64) NOT NULL, duplicate_review_status varchar(20) NOT NULL, category varchar(80) NOT NULL, primary_position varchar(80), origin_club_id bigint, origin_tournament_category_id bigint, source_site varchar(120), stage varchar(24) NOT NULL, pending_stage varchar(24), pending_reason varchar(1000), created_by bigint NOT NULL, created_at timestamp with time zone NOT NULL, updated_at timestamp with time zone NOT NULL, version bigint NOT NULL, anonymized_at timestamp with time zone)");
        jdbc.execute("CREATE TABLE scouting_assignments (prospect_id uuid NOT NULL, scout_user_id bigint NOT NULL, active boolean NOT NULL)");
        jdbc.execute("CREATE TABLE scouting_observation_reports (prospect_id uuid NOT NULL, scout_user_id bigint NOT NULL)");
        jdbc.execute("CREATE TABLE scouting_audit_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_user_id bigint, action varchar(80), resource_type varchar(40), resource_id varchar(80), metadata jsonb)");

        ObjectMapper json = new ObjectMapper();
        ScoutingCryptoService crypto = new ScoutingCryptoService("test-scouting-key", json);
        ScoutingSupport support = new ScoutingSupport(jdbc, crypto, json);
        ScoutingProspectService service = new ScoutingProspectService(support);
        long userId = 41;
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(
                new UsuarioAutenticado(userId, "Scout", List.of("SCOUT"), null), null, List.of()));

        UUID created = insertProspect(jdbc, crypto, userId, 0);
        UUID assigned = insertProspect(jdbc, crypto, 90, 1);
        UUID observed = insertProspect(jdbc, crypto, 90, 2);
        insertProspect(jdbc, crypto, 90, 3);
        jdbc.update("INSERT INTO scouting_assignments(prospect_id,scout_user_id,active) VALUES(?,?,true)", assigned, userId);
        jdbc.update("INSERT INTO scouting_observation_reports(prospect_id,scout_user_id) VALUES(?,?)", observed, userId);

        Map<String,Object> firstPage = service.listProspects(null, null, 0, 2);
        assertThat(firstPage).containsEntry("page", 0).containsEntry("size", 2)
                .containsEntry("totalElements", 3L).containsEntry("totalPages", 2L);
        assertThat((List<?>) firstPage.get("content"))
                .extracting(row -> ((Map<?,?>) row).get("id").toString())
                .containsExactly(created.toString(), assigned.toString());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM scouting_audit_events", Integer.class)).isEqualTo(2);

        Map<String,Object> secondPage = service.listProspects(null, null, 1, 2);
        assertThat(secondPage).containsEntry("page", 1).containsEntry("totalElements", 3L);
        assertThat((List<?>) secondPage.get("content"))
                .extracting(row -> ((Map<?,?>) row).get("id").toString())
                .containsExactly(observed.toString());
        assertThat(jdbc.queryForObject("SELECT count(*) FROM scouting_audit_events", Integer.class)).isEqualTo(3);
    }

    @Test
    void observationMustUseTheCriteriaSetAssignedToTheScout() {
        UUID assigned = UUID.randomUUID();
        ScoutingProspectService.requireAssignedCriteriaSet(assigned.toString(), assigned);

        assertStatus(HttpStatus.CONFLICT,
                () -> ScoutingProspectService.requireAssignedCriteriaSet(UUID.randomUUID(), assigned));
        assertStatus(HttpStatus.CONFLICT,
                () -> ScoutingProspectService.requireAssignedCriteriaSet(null, assigned));
    }

    @Test
    void exportAcceptsOnlyUniqueKnownSections() {
        assertThat(ScoutingProspectService.exportFields(List.of("profile", "history")))
                .containsExactly("profile", "history");

        assertStatus(HttpStatus.BAD_REQUEST, () -> ScoutingProspectService.exportFields(null));
        assertStatus(HttpStatus.BAD_REQUEST, () -> ScoutingProspectService.exportFields(List.of()));
        assertStatus(HttpStatus.BAD_REQUEST, () -> ScoutingProspectService.exportFields(List.of("profile", "profile")));
        assertStatus(HttpStatus.BAD_REQUEST, () -> ScoutingProspectService.exportFields(List.of("passwords")));
    }

    @Test
    void consentRequiresAnEvidenceReference() {
        assertThat(ScoutingContactService.requiredEvidenceReference(Map.of("evidenceReference", "acta-123")))
                .isEqualTo("acta-123");
        assertStatus(HttpStatus.BAD_REQUEST, () -> ScoutingContactService.requiredEvidenceReference(Map.of()));
        assertStatus(HttpStatus.BAD_REQUEST,
                () -> ScoutingContactService.requiredEvidenceReference(Map.of("evidenceReference", " ")));
        assertStatus(HttpStatus.BAD_REQUEST,
                () -> ScoutingContactService.requiredEvidenceReference(Map.of("evidenceReference", "x".repeat(501))));
    }

    private static void assertStatus(HttpStatus expected, Runnable action) {
        assertThatThrownBy(action::run)
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(error -> assertThat(((ResponseStatusException) error).getStatusCode().value())
                        .isEqualTo(expected.value()));
    }

    private static UUID insertProspect(JdbcTemplate jdbc, ScoutingCryptoService crypto, long createdBy, int ageDays) {
        UUID id = UUID.randomUUID();
        OffsetDateTime timestamp = OffsetDateTime.now().minusDays(ageDays);
        jdbc.update("""
                INSERT INTO scouting_prospects(id,sensitive_payload,identity_fingerprint,duplicate_review_status,
                    category,stage,created_by,created_at,updated_at,version)
                VALUES(?,?,?,'NOT_DUPLICATE','U16','DISCOVERED',?,?,?,0)
                """, id, crypto.encrypt(Map.of("firstName", "Alex", "lastName", "Scout", "birthDate", "2010-01-01")),
                crypto.fingerprint(id.toString()), createdBy, Timestamp.from(timestamp.toInstant()), Timestamp.from(timestamp.toInstant()));
        return id;
    }

    @AfterEach
    void clearSecurityContext() {
        SecurityContextHolder.clearContext();
    }
}
