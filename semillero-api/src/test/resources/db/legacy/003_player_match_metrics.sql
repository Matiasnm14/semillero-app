BEGIN;

CREATE TABLE IF NOT EXISTS player_match_metrics (
    metric_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id bigint NOT NULL CONSTRAINT fk_pmm_analysis REFERENCES analysis_jobs(id),
    match_id bigint NOT NULL CONSTRAINT fk_pmm_match REFERENCES partidos(id),
    player_id bigint NOT NULL CONSTRAINT fk_pmm_player REFERENCES jugadores(id),
    total_distance numeric(19, 6) NOT NULL,
    avg_speed numeric(19, 6) NOT NULL,
    max_speed numeric(19, 6) NOT NULL,
    period_start numeric(19, 6) NOT NULL,
    period_end numeric(19, 6) NOT NULL,
    version integer NOT NULL,
    is_current boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT chk_pmm_distance CHECK (total_distance BETWEEN 0 AND 9999999999999.999999),
    CONSTRAINT chk_pmm_speed CHECK (
        avg_speed BETWEEN 0 AND 9999999999999.999999
        AND max_speed BETWEEN avg_speed AND 9999999999999.999999),
    CONSTRAINT chk_pmm_period CHECK (
        period_start BETWEEN 0 AND 9999999999999.999999
        AND period_end > period_start AND period_end <= 9999999999999.999999),
    CONSTRAINT chk_pmm_version CHECK (version >= 1)
);

-- The existing unique key (partidos_id, jugadores_id) identifies participation in that match.
-- A referenced participation cannot be deleted or moved silently after metrics have been stored.
ALTER TABLE player_match_metrics
    ADD CONSTRAINT fk_pmm_participation FOREIGN KEY (match_id, player_id)
    REFERENCES participaciones_partido(partidos_id, jugadores_id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_pmm_analysis_player_period
    ON player_match_metrics(analysis_id, player_id, period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_pmm_match_player ON player_match_metrics(match_id, player_id);
CREATE INDEX IF NOT EXISTS idx_pmm_player ON player_match_metrics(player_id);

COMMIT;
