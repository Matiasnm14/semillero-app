-- Convocatorias de clubes, postulaciones de jugadores y solicitudes de contacto.
ALTER TABLE pruebas
    ADD COLUMN titulo varchar(120),
    ADD COLUMN lugar varchar(240),
    ADD COLUMN categoria varchar(40),
    ADD COLUMN cupos integer,
    ADD COLUMN descripcion text,
    ADD COLUMN requisitos text,
    ADD COLUMN estado varchar(20) NOT NULL DEFAULT 'ABIERTA';

CREATE TABLE prueba_posiciones (
    prueba_id bigint NOT NULL REFERENCES pruebas(id) ON DELETE CASCADE,
    posiciones_id bigint NOT NULL REFERENCES posiciones(id),
    PRIMARY KEY (prueba_id, posiciones_id)
);

CREATE TABLE solicitudes_contacto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id bigint NOT NULL REFERENCES clubes(id),
    jugador_id bigint NOT NULL REFERENCES jugadores(id),
    usuario_club_id bigint REFERENCES usuarios_club(id),
    asunto varchar(120) NOT NULL,
    mensaje varchar(500) NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_envio timestamp NOT NULL DEFAULT now(),
    fecha_respuesta timestamp,
    respuesta varchar(500),
    CONSTRAINT ck_solicitud_contacto_estado CHECK
        (estado IN ('PENDIENTE', 'VISTO', 'RESPONDIDO', 'RECHAZADO', 'ACEPTADO'))
);
CREATE INDEX idx_solicitudes_contacto_club_fecha
    ON solicitudes_contacto (club_id, fecha_envio DESC);
CREATE INDEX idx_solicitudes_contacto_jugador_fecha
    ON solicitudes_contacto (jugador_id, fecha_envio DESC);

CREATE TABLE inscripciones_prueba (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prueba_id bigint NOT NULL REFERENCES pruebas(id) ON DELETE CASCADE,
    jugador_id bigint NOT NULL REFERENCES jugadores(id),
    fecha_postulacion timestamp NOT NULL DEFAULT now(),
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE',
    nota varchar(500),
    nota_club varchar(500),
    CONSTRAINT uq_inscripcion_prueba_jugador UNIQUE (prueba_id, jugador_id),
    CONSTRAINT ck_inscripcion_prueba_estado CHECK
        (estado IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO', 'RETIRADO'))
);
CREATE INDEX idx_inscripciones_prueba_prueba_estado
    ON inscripciones_prueba (prueba_id, estado);
CREATE INDEX idx_inscripciones_prueba_jugador
    ON inscripciones_prueba (jugador_id, fecha_postulacion DESC);

ALTER TABLE notificaciones
    ADD COLUMN tipo varchar(40),
    ADD COLUMN referencia_id bigint,
    ADD COLUMN referencia_tipo varchar(40);
