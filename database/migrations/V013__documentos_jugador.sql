-- documentos_jugador: documentos y apto médico del jugador.
-- Tabla compartida que mantiene ficha técnica (punto 7 del acuerdo S1-04).
-- Torneos solo la lee, para validar la lista de buena fe (HU 5).
CREATE TABLE IF NOT EXISTS documentos_jugador (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugadores_id      bigint NOT NULL REFERENCES jugadores(id),
    tipo              varchar(25) NOT NULL
                      CHECK (tipo IN ('CI','CERTIFICADO_NACIMIENTO','APTO_MEDICO','AUTORIZACION_PADRES','SEGURO')),
    numero            varchar(30),
    fecha_emision     date,
    fecha_vencimiento date,
    estado            varchar(15) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (estado IN ('PENDIENTE','VIGENTE','VENCIDO','RECHAZADO'))
);

CREATE INDEX IF NOT EXISTS idx_documentos_jugador_jugador
    ON documentos_jugador (jugadores_id, tipo);
