-- Esquema base; reconcilia también las instalaciones anteriores a Flyway.
CREATE TABLE IF NOT EXISTS pais (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_pais varchar(30)
);

CREATE TABLE IF NOT EXISTS ciudad (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_ciudad varchar(30),
    pais_id bigint REFERENCES pais(id)
);

CREATE TABLE IF NOT EXISTS clubes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_club varchar(15),
    ciudad_id bigint REFERENCES ciudad(id)
);

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    email varchar(255),
    telefono_usuario varchar(20),
    doc_identidad_usuario varchar(20),
    password_hash varchar(255),
    nombres varchar(35),
    apellidos varchar(35)
);

CREATE TABLE IF NOT EXISTS administrador (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS usuarios_club (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS usuario_trabaja (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuarios_club_id bigint REFERENCES usuarios_club(id),
    tipo_usuario_club char(2),
    clubes_id bigint REFERENCES clubes(id)
);

CREATE TABLE IF NOT EXISTS jugadores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pierna_habil char(1),
    fecha_nacimiento date,
    altura double precision,
    peso double precision,
    descripcion_jugador varchar(255),
    users_id bigint REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS posiciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posicion varchar(100),
    codigo_posicion char(4)
);

CREATE TABLE IF NOT EXISTS posiciones_jugador (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posiciones_id bigint REFERENCES posiciones(id),
    jugadores_id bigint REFERENCES jugadores(id)
);

CREATE TABLE IF NOT EXISTS fichado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_fichaje timestamp(6) without time zone,
    fecha_final_fichaje timestamp(6) without time zone,
    jugadores_id bigint REFERENCES jugadores(id),
    clubes_id bigint REFERENCES clubes(id)
);

CREATE TABLE IF NOT EXISTS pruebas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_prueba date,
    hora_prueba time(6) without time zone,
    clubes_id bigint REFERENCES clubes(id),
    usuarios_club_id bigint REFERENCES usuarios_club(id)
);

CREATE TABLE IF NOT EXISTS clinica_de_pago (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio_clinica timestamp(6) without time zone,
    fecha_fin_clinica timestamp(6) without time zone,
    clubes_id bigint REFERENCES clubes(id),
    usuarios_club_id bigint REFERENCES usuarios_club(id)
);

CREATE TABLE IF NOT EXISTS videos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo_video varchar(100),
    link_video varchar(100),
    jugadores_id bigint REFERENCES jugadores(id)
);

CREATE TABLE IF NOT EXISTS conversa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje varchar(255),
    users_envia_id bigint REFERENCES users(id),
    users_recibe_id bigint REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS partidos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio timestamp(6) without time zone NOT NULL,
    fecha_fin timestamp(6) without time zone,
    club_local_id bigint NOT NULL REFERENCES clubes(id),
    club_visitante_id bigint NOT NULL REFERENCES clubes(id),
    estado varchar(20) NOT NULL,
    CONSTRAINT chk_clubes_distintos CHECK (club_local_id <> club_visitante_id),
    CONSTRAINT chk_partidos_estado CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO'))
);

CREATE INDEX IF NOT EXISTS idx_partidos_fecha_inicio ON partidos(fecha_inicio);
CREATE INDEX IF NOT EXISTS idx_partidos_local ON partidos(club_local_id);
CREATE INDEX IF NOT EXISTS idx_partidos_visitante ON partidos(club_visitante_id);

CREATE TABLE IF NOT EXISTS participaciones_partido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id bigint NOT NULL REFERENCES partidos(id),
    jugadores_id bigint NOT NULL REFERENCES jugadores(id),
    clubes_id bigint NOT NULL REFERENCES clubes(id),
    es_titular boolean NOT NULL,
    dorsal smallint,
    minuto_entrada smallint NOT NULL DEFAULT 0,
    minuto_salida smallint,
    velocidad_prom double precision,
    distancia_recorrida double precision,
    CONSTRAINT uk_participacion_jugador UNIQUE (partidos_id, jugadores_id)
);

CREATE INDEX IF NOT EXISTS idx_participacion_club ON participaciones_partido(partidos_id, clubes_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_clubes_distintos') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_clubes_distintos CHECK (club_local_id <> club_visitante_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partidos_estado') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partidos_estado CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO'));
    END IF;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='participaciones_partido'::regclass AND conname='uk_participacion_jugador') THEN
        ALTER TABLE participaciones_partido ADD CONSTRAINT uk_participacion_jugador UNIQUE (partidos_id, jugadores_id);
    END IF;
END;
$$;
