-- Control de acceso por roles (HU 16, tareas S2-01 a S2-04).
--
-- El punto 6 del acuerdo de la S1-04 le asignaba estas dos tablas a ficha
-- técnica, pero no las entregó y sin ellas la HU 16 no se puede cerrar, así que
-- las crea torneos. Son compartidas: sirven a los cuatro módulos.
--
-- El punto 21 del acuerdo manda derivar los cinco roles de lo que ya existe:
-- ADMIN sale de la tabla administrador y ENTRENADOR de
-- usuario_trabaja.tipo_usuario_club = 'EN'. ORGANIZADOR, MESA_CONTROL y
-- CONSULTA no tenían dónde vivir, y viven acá.
--
-- Idempotente, como el resto de las migraciones.

CREATE TABLE IF NOT EXISTS roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL,
    nombre varchar(60) NOT NULL,
    CONSTRAINT uk_rol_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS usuarios_roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint NOT NULL REFERENCES users(id),
    roles_id bigint NOT NULL REFERENCES roles(id),
    fecha_alta timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_rol UNIQUE (users_id, roles_id)
);

CREATE INDEX IF NOT EXISTS idx_usuarios_roles_usuario ON usuarios_roles(users_id);

-- Los cinco roles de la HU 16. RolesSeeder hace lo mismo al arrancar.
