-- Video original de partido; conserva tablas y datos existentes.
CREATE TABLE IF NOT EXISTS videos_partido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partido_id bigint NOT NULL REFERENCES partidos(id),
    storage_id varchar(36) NOT NULL,
    nombre_original varchar(255) NOT NULL,
    formato varchar(10) NOT NULL,
    tamano_bytes bigint NOT NULL CHECK (tamano_bytes > 0),
    duracion_segundos double precision CHECK (duracion_segundos > 0),
    sha256 varchar(64) NOT NULL,
    fecha_carga timestamp(6) with time zone NOT NULL,
    titulo_youtube varchar(100) NOT NULL,
    estado_youtube varchar(24) NOT NULL CHECK (estado_youtube IN (
        'DESHABILITADO', 'PENDIENTE', 'SUBIENDO', 'PROCESANDO', 'DISPONIBLE', 'ERROR', 'REVISION_REQUERIDA')),
    youtube_id varchar(11),
    error_youtube varchar(255),
    proximo_intento timestamp(6) with time zone,
    claim_token varchar(36),
    revision bigint NOT NULL DEFAULT 0,
    CONSTRAINT uk_video_partido_storage UNIQUE (storage_id)
);

CREATE INDEX IF NOT EXISTS idx_video_partido_partido ON videos_partido(partido_id, id);
CREATE INDEX IF NOT EXISTS idx_video_partido_cola ON videos_partido(estado_youtube, proximo_intento);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='videos_partido'::regclass AND conname='videos_partido_tamano_bytes_check') THEN
        ALTER TABLE videos_partido ADD CONSTRAINT videos_partido_tamano_bytes_check CHECK (tamano_bytes > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='videos_partido'::regclass AND conname='videos_partido_duracion_segundos_check') THEN
        ALTER TABLE videos_partido ADD CONSTRAINT videos_partido_duracion_segundos_check CHECK (duracion_segundos > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='videos_partido'::regclass AND conname='videos_partido_estado_youtube_check') THEN
        ALTER TABLE videos_partido ADD CONSTRAINT videos_partido_estado_youtube_check CHECK (estado_youtube IN ('DESHABILITADO', 'PENDIENTE', 'SUBIENDO', 'PROCESANDO', 'DISPONIBLE', 'ERROR', 'REVISION_REQUERIDA'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='videos_partido'::regclass AND conname='uk_video_partido_storage') THEN
        ALTER TABLE videos_partido ADD CONSTRAINT uk_video_partido_storage UNIQUE (storage_id);
    END IF;
END;
$$;
