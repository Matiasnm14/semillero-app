-- Módulo de Torneos (Grupo 4).
-- Las 16 tablas propias, las 2 compartidas que agrega torneos, y las columnas
-- que torneos suma a las tablas acordadas entre grupos.
--
-- Referencia: docs/torneos/bd_torneos_propuesta.sql (secciones C y D).
-- Todo es idempotente, como V000: se puede correr sobre una base que ya tenga
-- las tablas creadas por Hibernate con ddl-auto=update.

-- ---------------------------------------------------------------------------
-- Tablas propias de torneos
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS sedes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL,
    direccion varchar(150) NOT NULL,
    ciudad_id bigint NOT NULL REFERENCES ciudad(id)
);

CREATE TABLE IF NOT EXISTS canchas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sedes_id bigint NOT NULL REFERENCES sedes(id),
    nombre varchar(50) NOT NULL,
    tipo_superficie varchar(20) NOT NULL,
    largo_m numeric(5,1),
    ancho_m numeric(5,1),
    techada boolean NOT NULL DEFAULT false,
    iluminacion boolean NOT NULL DEFAULT false,
    vestuarios boolean NOT NULL DEFAULT false,
    descripcion varchar(255),
    activa boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_cancha_sede_nombre UNIQUE (sedes_id, nombre)
);

CREATE TABLE IF NOT EXISTS torneos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    temporada smallint NOT NULL,
    tipo varchar(15) NOT NULL,
    ambito varchar(10) NOT NULL DEFAULT 'INTERNO',
    organizador_externo varchar(100),
    formato varchar(25) NOT NULL,
    ida_vuelta boolean NOT NULL DEFAULT false,
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    fecha_limite_inscripcion date NOT NULL,
    estado varchar(25) NOT NULL DEFAULT 'BORRADOR',
    users_id bigint NOT NULL REFERENCES users(id),
    fecha_creacion timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT chk_torneo_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_torneo_limite_inscripcion CHECK (fecha_limite_inscripcion <= fecha_inicio),
    CONSTRAINT chk_torneo_organizador_externo CHECK (ambito = 'INTERNO' OR organizador_externo IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS reglamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneos_id bigint NOT NULL REFERENCES torneos(id),
    puntos_victoria smallint NOT NULL DEFAULT 3,
    puntos_empate smallint NOT NULL DEFAULT 1,
    puntos_derrota smallint NOT NULL DEFAULT 0,
    umbral_amarillas smallint NOT NULL DEFAULT 3,
    fechas_suspension_amarillas smallint NOT NULL DEFAULT 1,
    fechas_suspension_roja smallint NOT NULL DEFAULT 1,
    goles_walkover smallint NOT NULL DEFAULT 3,
    fecha_corte date NOT NULL,
    min_jugadores smallint NOT NULL,
    max_jugadores smallint NOT NULL,
    descanso_minimo_min smallint NOT NULL DEFAULT 60,
    CONSTRAINT uk_reglamento_torneo UNIQUE (torneos_id),
    CONSTRAINT chk_reglamento_jugadores CHECK (min_jugadores <= max_jugadores)
);

CREATE TABLE IF NOT EXISTS criterios_desempate (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL,
    nombre varchar(50) NOT NULL,
    CONSTRAINT uk_criterio_desempate_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS reglamento_desempates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reglamentos_id bigint NOT NULL REFERENCES reglamentos(id),
    criterios_desempate_id bigint NOT NULL REFERENCES criterios_desempate(id),
    orden smallint NOT NULL,
    CONSTRAINT uk_reglamento_desempate_orden UNIQUE (reglamentos_id, orden),
    CONSTRAINT uk_reglamento_desempate_criterio UNIQUE (reglamentos_id, criterios_desempate_id),
    CONSTRAINT chk_reglamento_desempate_orden CHECK (orden > 0)
);

CREATE TABLE IF NOT EXISTS torneo_categorias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneos_id bigint NOT NULL REFERENCES torneos(id),
    nombre varchar(20) NOT NULL,
    edad_minima smallint,
    edad_maxima smallint NOT NULL,
    cupo_maximo smallint NOT NULL,
    duracion_tiempo_min smallint NOT NULL,
    jugadores_en_cancha smallint NOT NULL,
    max_sustituciones smallint,
    CONSTRAINT uk_torneo_categoria_nombre UNIQUE (torneos_id, nombre),
    CONSTRAINT chk_torneo_categoria_cupo CHECK (cupo_maximo >= 2),
    CONSTRAINT chk_torneo_categoria_edades CHECK (edad_minima IS NULL OR edad_minima <= edad_maxima)
);

CREATE TABLE IF NOT EXISTS grupos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_categorias_id bigint NOT NULL REFERENCES torneo_categorias(id),
    nombre varchar(10) NOT NULL,
    CONSTRAINT uk_grupo_categoria_nombre UNIQUE (torneo_categorias_id, nombre)
);

CREATE TABLE IF NOT EXISTS inscripciones_equipo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_categorias_id bigint NOT NULL REFERENCES torneo_categorias(id),
    clubes_id bigint NOT NULL REFERENCES clubes(id),
    grupos_id bigint REFERENCES grupos(id),
    cabeza_serie smallint,
    estado varchar(15) NOT NULL DEFAULT 'PENDIENTE',
    motivo varchar(255),
    lista_confirmada boolean NOT NULL DEFAULT false,
    users_id bigint NOT NULL REFERENCES users(id),
    fecha_inscripcion timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uk_inscripcion_categoria_club UNIQUE (torneo_categorias_id, clubes_id),
    CONSTRAINT chk_inscripcion_motivo CHECK (estado NOT IN ('OBSERVADA','RECHAZADA') OR motivo IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS lista_buena_fe (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscripciones_equipo_id bigint NOT NULL REFERENCES inscripciones_equipo(id),
    torneos_id bigint NOT NULL REFERENCES torneos(id),
    jugadores_id bigint NOT NULL REFERENCES jugadores(id),
    posiciones_id bigint REFERENCES posiciones(id),
    dorsal smallint NOT NULL,
    habilitado boolean NOT NULL DEFAULT true,
    motivo_inhabilitacion varchar(255),
    fecha_alta timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uk_lista_bf_dorsal UNIQUE (inscripciones_equipo_id, dorsal),
    CONSTRAINT uk_lista_bf_jugador_torneo UNIQUE (torneos_id, jugadores_id),
    CONSTRAINT chk_lista_bf_dorsal CHECK (dorsal BETWEEN 1 AND 99)
);

CREATE TABLE IF NOT EXISTS reprogramaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id bigint NOT NULL REFERENCES partidos(id),
    fecha_inicio_anterior timestamp(6) without time zone,
    canchas_anterior_id bigint REFERENCES canchas(id),
    fecha_inicio_nueva timestamp(6) without time zone NOT NULL,
    canchas_nueva_id bigint NOT NULL REFERENCES canchas(id),
    motivo varchar(255) NOT NULL,
    users_id bigint NOT NULL REFERENCES users(id),
    fecha timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS planillas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id bigint NOT NULL REFERENCES partidos(id),
    estado varchar(15) NOT NULL DEFAULT 'BORRADOR',
    observaciones_arbitro text,
    users_id bigint NOT NULL REFERENCES users(id),
    fecha_confirmacion timestamp(6) without time zone,
    CONSTRAINT uk_planilla_partido UNIQUE (partidos_id)
);

CREATE TABLE IF NOT EXISTS planilla_cuerpo_tecnico (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planillas_id bigint NOT NULL REFERENCES planillas(id),
    clubes_id bigint NOT NULL REFERENCES clubes(id),
    nombre_completo varchar(100) NOT NULL,
    cargo varchar(30) NOT NULL,
    users_id bigint REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS eventos_partido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partidos_id bigint NOT NULL REFERENCES partidos(id),
    tipo varchar(10) NOT NULL,
    minuto smallint NOT NULL,
    participaciones_partido_id bigint NOT NULL REFERENCES participaciones_partido(id),
    participacion_rel_id bigint REFERENCES participaciones_partido(id),
    clubes_id bigint NOT NULL REFERENCES clubes(id),
    tipo_gol varchar(12),
    motivo varchar(150),
    users_id bigint NOT NULL REFERENCES users(id),
    fecha_registro timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT chk_evento_minuto CHECK (minuto BETWEEN 0 AND 130),
    CONSTRAINT chk_evento_gol_exige_tipo CHECK (tipo <> 'GOL' OR tipo_gol IS NOT NULL),
    CONSTRAINT chk_evento_no_gol_sin_tipo CHECK (tipo = 'GOL' OR tipo_gol IS NULL),
    CONSTRAINT chk_evento_cambio_exige_rel CHECK (tipo <> 'CAMBIO' OR participacion_rel_id IS NOT NULL),
    CONSTRAINT chk_evento_participaciones_distintas CHECK (participacion_rel_id IS DISTINCT FROM participaciones_partido_id)
);

CREATE TABLE IF NOT EXISTS sanciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista_buena_fe_id bigint NOT NULL REFERENCES lista_buena_fe(id),
    partidos_id bigint REFERENCES partidos(id),
    origen varchar(25) NOT NULL,
    fechas_suspension smallint NOT NULL,
    fechas_cumplidas smallint NOT NULL DEFAULT 0,
    motivo varchar(255),
    estado varchar(15) NOT NULL DEFAULT 'VIGENTE',
    users_id bigint REFERENCES users(id),
    fecha_registro timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT chk_sancion_fechas_suspension CHECK (fechas_suspension > 0),
    CONSTRAINT chk_sancion_fechas_cumplidas CHECK (fechas_cumplidas BETWEEN 0 AND fechas_suspension),
    CONSTRAINT chk_sancion_manual_motivo CHECK (origen <> 'MANUAL' OR motivo IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS apelaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sanciones_id bigint NOT NULL REFERENCES sanciones(id),
    motivo varchar(255) NOT NULL,
    estado varchar(15) NOT NULL DEFAULT 'PENDIENTE',
    resolucion varchar(255),
    fechas_resueltas smallint,
    users_id bigint NOT NULL REFERENCES users(id),
    resuelto_por bigint REFERENCES users(id),
    fecha_presentacion timestamp(6) without time zone NOT NULL DEFAULT now(),
    fecha_resolucion timestamp(6) without time zone
);

-- ---------------------------------------------------------------------------
-- Tablas compartidas que crea torneos (puntos 8 y 9 del acuerdo de la S1-04).
-- La columna modulo deja que las usen los cuatro grupos.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo varchar(20) NOT NULL,
    tabla varchar(50) NOT NULL,
    registro_id bigint,
    accion varchar(30) NOT NULL,
    valor_anterior jsonb,
    valor_nuevo jsonb,
    motivo varchar(255),
    users_id bigint REFERENCES users(id),
    fecha timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notificaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id bigint NOT NULL REFERENCES users(id),
    modulo varchar(20) NOT NULL,
    titulo varchar(100) NOT NULL,
    mensaje varchar(500) NOT NULL,
    leida boolean NOT NULL DEFAULT false,
    fecha timestamp(6) without time zone NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Índices
-- ---------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_lista_bf_jugador ON lista_buena_fe(jugadores_id);
CREATE INDEX IF NOT EXISTS idx_eventos_partido ON eventos_partido(partidos_id);
CREATE INDEX IF NOT EXISTS idx_sanciones_estado ON sanciones(estado);
CREATE INDEX IF NOT EXISTS idx_auditoria_tabla ON auditoria(tabla, registro_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha ON auditoria(fecha);
CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario ON notificaciones(users_id, leida);

