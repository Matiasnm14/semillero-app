-- ---------------------------------------------------------------------------
-- Restricciones e índices de esas columnas, idempotentes como en V000
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_torneo_fase') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_torneo_fase CHECK (torneo_categorias_id IS NULL OR fase IS NOT NULL);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_walkover_club') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_walkover_club CHECK (ganador_walkover_id IS NULL OR ganador_walkover_id IN (club_local_id, club_visitante_id));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_fechas') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_fechas CHECK (fecha_fin IS NULL OR fecha_fin > fecha_inicio);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_goles_local') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_goles_local CHECK (goles_local >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_goles_visitante') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_goles_visitante CHECK (goles_visitante >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_penales_local') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_penales_local CHECK (penales_local >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='partidos'::regclass AND conname='chk_partido_penales_visitante') THEN
        ALTER TABLE partidos ADD CONSTRAINT chk_partido_penales_visitante CHECK (penales_visitante >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='participaciones_partido'::regclass AND conname='chk_participacion_minutos') THEN
        ALTER TABLE participaciones_partido ADD CONSTRAINT chk_participacion_minutos CHECK (minutos_jugados >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='jugadores'::regclass AND conname='chk_jugador_estado') THEN
        ALTER TABLE jugadores ADD CONSTRAINT chk_jugador_estado CHECK (estado IN ('ACTIVO','LESIONADO','INACTIVO','BAJA'));
    END IF;
END;
$$;

