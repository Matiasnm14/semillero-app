-- Scouting lives beside the shared Semillero model. It never mutates player/club data.
CREATE TABLE IF NOT EXISTS scouting_prospects (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sensitive_payload bytea NOT NULL,
    identity_fingerprint varchar(64) NOT NULL,
    duplicate_review_status varchar(20) NOT NULL DEFAULT 'NEEDS_REVIEW'
        CHECK(duplicate_review_status IN ('NEEDS_REVIEW','CONFIRMED_DUPLICATE','NOT_DUPLICATE')),
    merged_into_prospect_id uuid REFERENCES scouting_prospects(id),
    duplicate_reviewed_by bigint REFERENCES users(id),
    duplicate_reviewed_at timestamptz,
    category varchar(80) NOT NULL,
    primary_position varchar(80),
    origin_club_id bigint REFERENCES clubes(id),
    origin_tournament_category_id bigint REFERENCES torneo_categorias(id),
    source_site varchar(120),
    stage varchar(24) NOT NULL DEFAULT 'DISCOVERED'
        CHECK (stage IN ('DISCOVERED','PRESELECTED','OBSERVING','OBSERVED','EVALUATED','RECOMMENDED',
                         'CONTACTED','TRIAL','ACCEPTED','INCORPORATED','DISCARDED','ARCHIVED')),
    pending_stage varchar(24),
    pending_reason varchar(1000),
    pending_requested_by bigint REFERENCES users(id),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    anonymized_at timestamptz,
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_scouting_prospect_fingerprint ON scouting_prospects(identity_fingerprint);
CREATE INDEX IF NOT EXISTS idx_scouting_prospect_stage ON scouting_prospects(stage, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_scouting_prospect_category ON scouting_prospects(category, source_site);
CREATE TABLE IF NOT EXISTS scouting_duplicate_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    canonical_prospect_id uuid REFERENCES scouting_prospects(id),
    decision varchar(20) NOT NULL CHECK(decision IN ('CONFIRMED_DUPLICATE','NOT_DUPLICATE','MERGED')),
    reason varchar(1000) NOT NULL,
    reviewed_by bigint NOT NULL REFERENCES users(id),
    reviewed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS scouting_user_scopes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category varchar(80),
    site varchar(120),
    granted_by bigint NOT NULL REFERENCES users(id),
    granted_at timestamptz NOT NULL DEFAULT now(),
    active boolean NOT NULL DEFAULT true,
    revoked_by bigint REFERENCES users(id),
    revoked_at timestamptz,
    CHECK (category IS NOT NULL OR site IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_scouting_scopes_user ON scouting_user_scopes(user_id);

CREATE TABLE IF NOT EXISTS scouting_oidc_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer varchar(500) NOT NULL,
    subject varchar(255) NOT NULL,
    users_id bigint NOT NULL REFERENCES users(id),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    active boolean NOT NULL DEFAULT true,
    UNIQUE(issuer,subject),
    UNIQUE(issuer,users_id)
);

CREATE TABLE IF NOT EXISTS scouting_criteria_sets (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    category varchar(80) NOT NULL,
    version integer NOT NULL CHECK(version > 0),
    title varchar(160) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED','RETIRED')),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(category, version)
);
CREATE TABLE IF NOT EXISTS scouting_criteria (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    criteria_set_id uuid NOT NULL REFERENCES scouting_criteria_sets(id),
    dimension varchar(16) NOT NULL CHECK(dimension IN ('TECHNICAL','TACTICAL','PHYSICAL','PSYCHOLOGICAL')),
    code varchar(80) NOT NULL,
    label varchar(160) NOT NULL,
    observable_behavior varchar(1000) NOT NULL,
    anchors jsonb NOT NULL CHECK(jsonb_typeof(anchors) = 'array'),
    display_order integer NOT NULL DEFAULT 0,
    UNIQUE(criteria_set_id, code)
);

CREATE TABLE IF NOT EXISTS scouting_assignments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    scout_user_id bigint NOT NULL REFERENCES users(id),
    assigned_by bigint NOT NULL REFERENCES users(id),
    match_id bigint REFERENCES partidos(id),
    due_at timestamptz,
    location varchar(240),
    form_version varchar(40) NOT NULL DEFAULT '1',
    reason varchar(1000),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    active boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS idx_scouting_assignments_scout ON scouting_assignments(scout_user_id, active, due_at);
CREATE INDEX IF NOT EXISTS idx_scouting_assignments_prospect ON scouting_assignments(prospect_id, active);

CREATE TABLE IF NOT EXISTS scouting_observation_reports (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    assignment_id uuid REFERENCES scouting_assignments(id),
    scout_user_id bigint NOT NULL REFERENCES users(id),
    match_id bigint REFERENCES partidos(id),
    observed_at timestamptz NOT NULL,
    opponent varchar(160),
    played_position varchar(80),
    minutes_played smallint CHECK(minutes_played IS NULL OR minutes_played BETWEEN 0 AND 180),
    current_performance smallint CHECK(current_performance IS NULL OR current_performance BETWEEN 1 AND 5),
    potential smallint CHECK(potential IS NULL OR potential BETWEEN 1 AND 5),
    confidence varchar(8) NOT NULL CHECK(confidence IN ('LOW','MEDIUM','HIGH')),
    criteria_set_id uuid NOT NULL REFERENCES scouting_criteria_sets(id),
    narrative_cipher bytea,
    idempotency_key varchar(120) NOT NULL,
    request_fingerprint varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(scout_user_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_scouting_reports_prospect_date ON scouting_observation_reports(prospect_id, observed_at DESC);
CREATE TABLE IF NOT EXISTS scouting_report_evidence (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    report_id uuid NOT NULL REFERENCES scouting_observation_reports(id) ON DELETE CASCADE,
    evidence_type varchar(12) NOT NULL CHECK(evidence_type IN ('VIDEO','PHOTO','DOCUMENT')),
    uri varchar(1000) NOT NULL,
    description varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(report_id,uri)
);
CREATE TABLE IF NOT EXISTS scouting_observation_scores (
    report_id uuid NOT NULL REFERENCES scouting_observation_reports(id) ON DELETE CASCADE,
    criterion_id uuid NOT NULL REFERENCES scouting_criteria(id),
    observed boolean NOT NULL,
    score smallint,
    note_cipher bytea,
    PRIMARY KEY(report_id, criterion_id),
    CHECK ((observed AND score BETWEEN 1 AND 5) OR (NOT observed AND score IS NULL))
);

CREATE TABLE IF NOT EXISTS scouting_stage_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    from_stage varchar(24),
    to_stage varchar(24) NOT NULL,
    reason varchar(1000) NOT NULL,
    changed_by bigint NOT NULL REFERENCES users(id),
    reviewed_by bigint REFERENCES users(id),
    evidence_reference varchar(500),
    changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_scouting_stage_history_prospect ON scouting_stage_history(prospect_id, changed_at);
CREATE TABLE IF NOT EXISTS scouting_exports (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    requested_by bigint NOT NULL REFERENCES users(id),
    payload_cipher bytea NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    downloaded_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_scouting_exports_expiry ON scouting_exports(expires_at);

CREATE TABLE IF NOT EXISTS scouting_tutor_consents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    tutor_payload_cipher bytea NOT NULL,
    channel varchar(24) NOT NULL CHECK(channel IN ('IN_PERSON','EMAIL','PHONE','DOCUMENT','PORTAL')),
    evidence_reference varchar(500),
    granted_at timestamptz NOT NULL,
    granted_by bigint NOT NULL REFERENCES users(id),
    revoked_at timestamptz,
    revoked_by bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_scouting_consent_current ON scouting_tutor_consents(prospect_id, revoked_at, granted_at DESC);

CREATE TABLE IF NOT EXISTS scouting_message_templates (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    code varchar(80) NOT NULL,
    version integer NOT NULL CHECK(version > 0),
    audience varchar(12) NOT NULL CHECK(audience IN ('ADULT','TUTOR')),
    body text NOT NULL,
    approved boolean NOT NULL DEFAULT false,
    created_by bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(code, version)
);
CREATE TABLE IF NOT EXISTS scouting_communications (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    consent_id uuid REFERENCES scouting_tutor_consents(id),
    template_id uuid NOT NULL REFERENCES scouting_message_templates(id),
    channel varchar(8) NOT NULL CHECK(channel IN ('EMAIL','PHONE')),
    recipient_cipher bytea NOT NULL,
    content_cipher bytea NOT NULL,
    content_fingerprint varchar(64) NOT NULL,
    status varchar(24) NOT NULL DEFAULT 'QUEUED'
        CHECK(status IN ('QUEUED','PENDING_CONFIGURATION','SENT','DELIVERY_FAILED','CANCELLED')),
    requested_by bigint NOT NULL REFERENCES users(id),
    requested_at timestamptz NOT NULL DEFAULT now(),
    sent_at timestamptz,
    idempotency_key varchar(120) NOT NULL,
    request_fingerprint varchar(64) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    last_error varchar(500),
    UNIQUE(requested_by, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_scouting_communications_prospect ON scouting_communications(prospect_id, requested_at DESC);

CREATE TABLE IF NOT EXISTS scouting_trials (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    prospect_id uuid NOT NULL REFERENCES scouting_prospects(id),
    scheduled_at timestamptz NOT NULL,
    location varchar(240) NOT NULL,
    club_id bigint REFERENCES clubes(id),
    evaluator_user_id bigint NOT NULL REFERENCES users(id),
    invitation_accepted boolean NOT NULL DEFAULT false,
    status varchar(16) NOT NULL DEFAULT 'SCHEDULED' CHECK(status IN ('SCHEDULED','COMPLETED','CANCELLED')),
    outcome varchar(16) CHECK(outcome IS NULL OR outcome IN ('ACCEPT','REJECT','REASSESS')),
    outcome_reason varchar(1000),
    completed_at timestamptz,
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_scouting_trials_prospect ON scouting_trials(prospect_id, scheduled_at DESC);

CREATE TABLE IF NOT EXISTS scouting_player_links (
    prospect_id uuid PRIMARY KEY REFERENCES scouting_prospects(id),
    player_id bigint NOT NULL UNIQUE REFERENCES jugadores(id),
    linked_by bigint NOT NULL REFERENCES users(id),
    linked_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS scouting_outbox (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    event_type varchar(100) NOT NULL,
    aggregate_id uuid NOT NULL,
    idempotency_key varchar(160) NOT NULL UNIQUE,
    payload jsonb NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PUBLISHED','FAILED')),
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    last_error varchar(500)
);
CREATE INDEX IF NOT EXISTS idx_scouting_outbox_pending ON scouting_outbox(next_attempt_at) WHERE status='PENDING';

CREATE TABLE IF NOT EXISTS scouting_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id bigint REFERENCES users(id),
    action varchar(80) NOT NULL,
    resource_type varchar(40) NOT NULL,
    resource_id varchar(80),
    occurred_at timestamptz NOT NULL DEFAULT now(),
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_scouting_audit_resource ON scouting_audit_events(resource_type, resource_id, occurred_at);

CREATE TABLE IF NOT EXISTS scouting_security_alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type varchar(80) NOT NULL,
    user_id bigint REFERENCES users(id),
    window_started_at timestamptz NOT NULL,
    last_observed_at timestamptz NOT NULL DEFAULT now(),
    occurrence_count integer NOT NULL,
    acknowledged_at timestamptz,
    acknowledged_by bigint REFERENCES users(id),
    UNIQUE(alert_type,user_id,window_started_at)
);
CREATE INDEX IF NOT EXISTS idx_scouting_security_alerts_open ON scouting_security_alerts(acknowledged_at,last_observed_at DESC);

