-- Migración administrada por Flyway; compatible con instalaciones previas.
CREATE TABLE IF NOT EXISTS analysis_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_partido_id bigint NOT NULL REFERENCES videos_partido(id),
    estado varchar(16) NOT NULL,
    fecha_solicitud timestamp(6) with time zone NOT NULL,
    fecha_inicio timestamp(6) with time zone,
    fecha_fin timestamp(6) with time zone,
    fecha_actualizacion timestamp(6) with time zone NOT NULL,
    porcentaje double precision,
    fotogramas_procesados bigint,
    fotogramas_totales bigint,
    resultados_disponibles boolean NOT NULL DEFAULT false,
    resultado_ref varchar(255),
    codigo_error varchar(40),
    mensaje_error varchar(255),
    enviado boolean NOT NULL DEFAULT false,
    revision_remota bigint,
    fallos_consecutivos integer NOT NULL DEFAULT 0,
    proxima_ejecucion timestamp(6) with time zone,
    claim_token varchar(36),
    lease_until timestamp(6) with time zone,
    revision bigint NOT NULL DEFAULT 0
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_state') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_state CHECK (estado IN ('PENDIENTE', 'PROCESANDO', 'COMPLETADO', 'ERROR'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_percentage') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_percentage CHECK (porcentaje >= 0 AND porcentaje <= 100);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_frames') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_frames CHECK (
        (fotogramas_procesados IS NULL OR fotogramas_procesados >= 0)
        AND (fotogramas_totales IS NULL OR fotogramas_totales > 0)
        AND (fotogramas_procesados IS NULL OR fotogramas_totales IS NULL OR fotogramas_procesados <= fotogramas_totales));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_dates') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_dates CHECK (
        (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
        AND ((estado = 'PENDIENTE' AND fecha_inicio IS NULL AND fecha_fin IS NULL)
          OR (estado = 'PROCESANDO' AND fecha_inicio IS NOT NULL AND fecha_fin IS NULL)
          OR (estado = 'COMPLETADO' AND fecha_inicio IS NOT NULL AND fecha_fin IS NOT NULL)
          OR (estado = 'ERROR' AND fecha_fin IS NOT NULL)));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_results') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_results CHECK (
        (NOT resultados_disponibles OR (estado = 'COMPLETADO' AND resultado_ref IS NOT NULL AND length(trim(resultado_ref)) > 0))
        AND (estado = 'COMPLETADO' OR resultado_ref IS NULL));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_revision') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_revision CHECK (revision_remota >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_failures') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_failures CHECK (fallos_consecutivos >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_lease') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_lease CHECK ((claim_token IS NULL) = (lease_until IS NULL));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='analysis_jobs'::regclass AND conname='chk_analysis_queue') THEN
        ALTER TABLE analysis_jobs ADD CONSTRAINT chk_analysis_queue CHECK (
        (estado IN ('PENDIENTE', 'PROCESANDO') AND proxima_ejecucion IS NOT NULL)
        OR (estado IN ('COMPLETADO', 'ERROR') AND proxima_ejecucion IS NULL));
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS idx_analysis_video ON analysis_jobs(video_partido_id, id);
CREATE INDEX IF NOT EXISTS idx_analysis_queue ON analysis_jobs(estado, proxima_ejecucion);
CREATE UNIQUE INDEX IF NOT EXISTS uk_analysis_active_video ON analysis_jobs(video_partido_id)
    WHERE estado IN ('PENDIENTE', 'PROCESANDO');
